/**
 * @module nest-template/models/Article
 * @description Knowledge-base article with per-operation permissions.
 */
import {
  BaseModel,
  column,
  createdBy,
  defaultQueryAttr,
  pk,
  table,
  updatedBy,
} from "@decaf-ts/core";
import { readonly } from "@decaf-ts/db-decorators";
import { uses } from "@decaf-ts/decoration";
import {
  maxlength,
  minlength,
  model,
  pattern,
  required,
  type ModelArg,
} from "@decaf-ts/decorator-validation";
import { PersistenceFlavour } from "../persistence/flavour";

/**
 * @description A knowledge-base article.
 * @summary The model itself carries no auth metadata: its controller is generated by hand
 * (see `controllers/article.controller.ts`) and decorated route by route:
 * - `read` (GET /article/:slug) — `@Public()`;
 * - lists and queries — `@RequireRoles("reader")`;
 * - `create`/`update` — `@RequireRoles("editor")`;
 * - `delete` — `@RequireRoles("admin")`.
 * @class Article
 */
@uses(PersistenceFlavour)
@table("article")
@model()
export class Article extends BaseModel {
  @pk({ type: String, generated: false })
  @pattern(/^[a-z0-9-]{3,80}$/)
  slug!: string;

  @column()
  @required()
  @minlength(3)
  @maxlength(120)
  @defaultQueryAttr()
  title!: string;

  @column()
  @required()
  @minlength(3)
  body!: string;

  @column()
  @required()
  topic!: string;

  @column()
  @createdBy()
  @readonly()
  createdBy!: string;

  @column()
  @updatedBy()
  updatedBy!: string;

  constructor(arg?: ModelArg<Article>) {
    super(arg);
  }
}
